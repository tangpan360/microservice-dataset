#!/usr/bin/env python3

from __future__ import annotations

import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Build local subgraph candidates for selected target services."
    )
    parser.add_argument(
        "--target-services-csv",
        type=Path,
        required=True,
        help="Path to target_services.csv generated by filter_services_from_metadata.py",
    )
    parser.add_argument(
        "--edge-root",
        type=Path,
        required=True,
        help="Path to service_call_edge_minute directory (contains day=*/part-000.csv)",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help="Output directory for subgraph candidate files (default: sibling of service_metadata under run dir)",
    )
    parser.add_argument(
        "--max-targets",
        type=int,
        default=None,
        help="Only keep the first N target services from target_services.csv.",
    )
    parser.add_argument("--max-hop", type=int, default=2, choices=[1, 2])
    parser.add_argument(
        "--max-nodes",
        type=int,
        default=100,
        help="Maximum number of nodes kept for each target subgraph.",
    )
    parser.add_argument("--topk-in", type=int, default=10)
    parser.add_argument("--topk-out", type=int, default=10)
    parser.add_argument("--topk-next-hop", type=int, default=5)
    return parser.parse_args()


def safe_int(value: str | None, default: int = 0) -> int:
    if value is None:
        return default
    text = str(value).strip()
    if not text:
        return default
    try:
        return int(float(text))
    except ValueError:
        return default


def safe_float(value: str | None, default: float = 0.0) -> float:
    if value is None:
        return default
    text = str(value).strip()
    if not text:
        return default
    try:
        return float(text)
    except ValueError:
        return default


def write_csv(path: Path, fieldnames: list[str], rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow(row)


def load_targets(path: Path) -> list[dict]:
    rows: list[dict] = []
    with path.open("r", encoding="utf-8", newline="") as fh:
        reader = csv.DictReader(fh)
        for row in reader:
            rows.append(
                {
                    "service": row["service"].strip(),
                    "service_idx": safe_int(row.get("service_idx")),
                }
            )
    return rows


def aggregate_edges(edge_root: Path):
    edge_weight: dict[tuple[str, str], float] = defaultdict(float)
    idx_map: dict[str, int] = {}
    edge_files = sorted(edge_root.glob("day=*/*.csv"))
    if not edge_files:
        raise RuntimeError(f"No edge csv files found under {edge_root}")
    for path in edge_files:
        with path.open("r", encoding="utf-8", newline="") as fh:
            reader = csv.DictReader(fh)
            for row in reader:
                caller = row["caller_service"].strip()
                callee = row["callee_service"].strip()
                if not caller or not callee:
                    continue
                weight = safe_float(row.get("call_count"))
                edge_weight[(caller, callee)] += weight
                idx_map.setdefault(caller, safe_int(row.get("caller_idx")))
                idx_map.setdefault(callee, safe_int(row.get("callee_idx")))
    incoming: dict[str, list[tuple[str, float]]] = defaultdict(list)
    outgoing: dict[str, list[tuple[str, float]]] = defaultdict(list)
    for (caller, callee), weight in edge_weight.items():
        incoming[callee].append((caller, weight))
        outgoing[caller].append((callee, weight))
    for svc in incoming:
        incoming[svc].sort(key=lambda item: (-item[1], item[0]))
    for svc in outgoing:
        outgoing[svc].sort(key=lambda item: (-item[1], item[0]))
    return edge_weight, incoming, outgoing, idx_map


def add_neighbors(
    *,
    source_service: str,
    source_hop: int,
    relation: str,
    neighbors: list[tuple[str, float]],
    topk: int,
    next_hop: int,
    nodes: dict[str, dict],
    frontier: set[str],
    idx_map: dict[str, int],
    max_nodes: int,
) -> None:
    for neighbor, weight in neighbors[:topk]:
        if len(nodes) >= max_nodes:
            break
        if neighbor not in nodes:
            nodes[neighbor] = {
                "service": neighbor,
                "service_idx": idx_map.get(neighbor, -1),
                "min_hop": next_hop,
                "relation": relation,
                "parent_service": source_service,
                "edge_weight_from_parent": weight,
            }
            frontier.add(neighbor)
        else:
            if next_hop < nodes[neighbor]["min_hop"]:
                nodes[neighbor]["min_hop"] = next_hop
                nodes[neighbor]["relation"] = relation
                nodes[neighbor]["parent_service"] = source_service
                nodes[neighbor]["edge_weight_from_parent"] = weight


def build_subgraph_for_target(
    *,
    target_service: str,
    target_idx: int,
    incoming: dict[str, list[tuple[str, float]]],
    outgoing: dict[str, list[tuple[str, float]]],
    idx_map: dict[str, int],
    max_hop: int,
    topk_in: int,
    topk_out: int,
    topk_next_hop: int,
    max_nodes: int,
) -> dict[str, dict]:
    nodes: dict[str, dict] = {
        target_service: {
            "service": target_service,
            "service_idx": target_idx,
            "min_hop": 0,
            "relation": "target",
            "parent_service": "",
            "edge_weight_from_parent": 0.0,
        }
    }

    frontier: set[str] = set()
    add_neighbors(
        source_service=target_service,
        source_hop=0,
        relation="upstream_1hop",
        neighbors=incoming.get(target_service, []),
        topk=topk_in,
        next_hop=1,
        nodes=nodes,
        frontier=frontier,
        idx_map=idx_map,
        max_nodes=max_nodes,
    )
    add_neighbors(
        source_service=target_service,
        source_hop=0,
        relation="downstream_1hop",
        neighbors=outgoing.get(target_service, []),
        topk=topk_out,
        next_hop=1,
        nodes=nodes,
        frontier=frontier,
        idx_map=idx_map,
        max_nodes=max_nodes,
    )

    if max_hop >= 2 and len(nodes) < max_nodes:
        frontier_1hop = sorted(frontier)
        frontier = set()
        for service in frontier_1hop:
            if len(nodes) >= max_nodes:
                break
            add_neighbors(
                source_service=service,
                source_hop=1,
                relation="upstream_2hop",
                neighbors=incoming.get(service, []),
                topk=topk_next_hop,
                next_hop=2,
                nodes=nodes,
                frontier=frontier,
                idx_map=idx_map,
                max_nodes=max_nodes,
            )
            if len(nodes) >= max_nodes:
                break
            add_neighbors(
                source_service=service,
                source_hop=1,
                relation="downstream_2hop",
                neighbors=outgoing.get(service, []),
                topk=topk_next_hop,
                next_hop=2,
                nodes=nodes,
                frontier=frontier,
                idx_map=idx_map,
                max_nodes=max_nodes,
            )
    return nodes


def main() -> None:
    args = parse_args()
    targets = load_targets(args.target_services_csv)
    if not targets:
        raise RuntimeError(f"No target services found in {args.target_services_csv}")
    if args.max_targets is not None:
        targets = targets[: args.max_targets]

    if args.output_dir is None:
        output_dir = args.target_services_csv.parents[1] / "subgraph_candidates"
    else:
        output_dir = args.output_dir

    edge_weight, incoming, outgoing, idx_map = aggregate_edges(args.edge_root)

    node_rows: list[dict] = []
    edge_rows: list[dict] = []
    summary_rows: list[dict] = []

    for target in targets:
        target_service = target["service"]
        target_idx = target["service_idx"]
        nodes = build_subgraph_for_target(
            target_service=target_service,
            target_idx=target_idx,
            incoming=incoming,
            outgoing=outgoing,
            idx_map=idx_map,
            max_hop=args.max_hop,
            topk_in=args.topk_in,
            topk_out=args.topk_out,
            topk_next_hop=args.topk_next_hop,
            max_nodes=args.max_nodes,
        )
        selected_services = set(nodes)

        for node in sorted(nodes.values(), key=lambda row: (row["min_hop"], row["service_idx"], row["service"])):
            node_rows.append(
                {
                    "target_service": target_service,
                    "target_service_idx": target_idx,
                    "service": node["service"],
                    "service_idx": node["service_idx"],
                    "min_hop": node["min_hop"],
                    "relation": node["relation"],
                    "parent_service": node["parent_service"],
                    "edge_weight_from_parent": node["edge_weight_from_parent"],
                }
            )

        local_edge_count = 0
        for (caller, callee), weight in edge_weight.items():
            if caller in selected_services and callee in selected_services:
                local_edge_count += 1
                edge_rows.append(
                    {
                        "target_service": target_service,
                        "target_service_idx": target_idx,
                        "caller_service": caller,
                        "caller_idx": idx_map.get(caller, -1),
                        "callee_service": callee,
                        "callee_idx": idx_map.get(callee, -1),
                        "aggregate_call_count": weight,
                        "caller_hop": nodes[caller]["min_hop"],
                        "callee_hop": nodes[callee]["min_hop"],
                    }
                )

        summary_rows.append(
            {
                "target_service": target_service,
                "target_service_idx": target_idx,
                "node_count": len(selected_services),
                "edge_count": local_edge_count,
                "max_hop": args.max_hop,
            }
        )

    write_csv(
        output_dir / "target_subgraph_nodes.csv",
        [
            "target_service",
            "target_service_idx",
            "service",
            "service_idx",
            "min_hop",
            "relation",
            "parent_service",
            "edge_weight_from_parent",
        ],
        node_rows,
    )
    write_csv(
        output_dir / "target_subgraph_edges.csv",
        [
            "target_service",
            "target_service_idx",
            "caller_service",
            "caller_idx",
            "callee_service",
            "callee_idx",
            "aggregate_call_count",
            "caller_hop",
            "callee_hop",
        ],
        edge_rows,
    )
    write_csv(
        output_dir / "target_subgraph_summary.csv",
        [
            "target_service",
            "target_service_idx",
            "node_count",
            "edge_count",
            "max_hop",
        ],
        summary_rows,
    )

    summary = {
        "target_services_csv": str(args.target_services_csv),
        "edge_root": str(args.edge_root),
        "output_dir": str(output_dir),
        "target_count": len(targets),
        "max_nodes": args.max_nodes,
        "max_hop": args.max_hop,
        "topk_in": args.topk_in,
        "topk_out": args.topk_out,
        "topk_next_hop": args.topk_next_hop,
    }
    (output_dir / "target_subgraph_summary.json").write_text(
        json.dumps(summary, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    print(f"[OK] targets={len(targets)} output={output_dir}")


if __name__ == "__main__":
    main()
