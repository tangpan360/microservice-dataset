#!/usr/bin/env python3

from __future__ import annotations

import argparse
import csv
import json
import math
from pathlib import Path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Select target services from ali2022 service_metadata.csv."
    )
    parser.add_argument(
        "--metadata-csv",
        type=Path,
        required=True,
        help="Path to service_metadata.csv generated by build_ali2022_intermediate.py",
    )
    parser.add_argument(
        "--output-csv",
        type=Path,
        default=None,
        help="Output path for target_services.csv (default: same dir as metadata)",
    )
    parser.add_argument(
        "--summary-json",
        type=Path,
        default=None,
        help="Optional summary json path (default: same dir as metadata)",
    )
    parser.add_argument("--min-active-minutes", type=int, default=360)
    parser.add_argument("--min-nonzero-minutes", type=int, default=60)
    parser.add_argument("--min-nonzero-ratio", type=float, default=0.10)
    parser.add_argument(
        "--min-total-in-quantile",
        type=float,
        default=0.50,
        help="Quantile threshold for total_in_calls among services passing hard filters.",
    )
    return parser.parse_args()


def safe_int(value: str | None, default: int = 0) -> int:
    if value is None:
        return default
    text = str(value).strip()
    if not text:
        return default
    try:
        return int(float(text))
    except ValueError:
        return default


def safe_float(value: str | None, default: float = 0.0) -> float:
    if value is None:
        return default
    text = str(value).strip()
    if not text:
        return default
    try:
        return float(text)
    except ValueError:
        return default


def quantile(values: list[float], q: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    if len(ordered) == 1:
        return float(ordered[0])
    pos = max(0.0, min(1.0, q)) * (len(ordered) - 1)
    low = math.floor(pos)
    high = math.ceil(pos)
    if low == high:
        return float(ordered[low])
    frac = pos - low
    return float(ordered[low] * (1 - frac) + ordered[high] * frac)


def load_rows(path: Path) -> list[dict]:
    rows: list[dict] = []
    with path.open("r", encoding="utf-8", newline="") as fh:
        reader = csv.DictReader(fh)
        for row in reader:
            active = safe_int(row.get("total_active_minutes"))
            nonzero = safe_int(row.get("nonzero_in_minutes"))
            total_in = safe_float(row.get("total_in_calls"))
            total_out = safe_float(row.get("total_out_calls"))
            avg_in = safe_float(row.get("avg_in_calls"))
            max_in = safe_float(row.get("max_in_calls"))
            first_seen = safe_int(row.get("first_seen_timestamp_bucket_s"))
            last_seen = safe_int(row.get("last_seen_timestamp_bucket_s"))
            span_minutes = ((last_seen - first_seen) // 60 + 1) if last_seen >= first_seen else 0
            nonzero_ratio = (nonzero / active) if active > 0 else 0.0
            burst_ratio = (max_in / avg_in) if avg_in > 0 else max_in
            quality_score = (
                math.log1p(total_in)
                + 0.5 * nonzero_ratio
                + 0.2 * math.log1p(active)
                - 0.05 * math.log1p(max(burst_ratio, 0.0))
            )
            rows.append(
                {
                    "service": row.get("service", ""),
                    "service_idx": safe_int(row.get("service_idx")),
                    "first_seen_timestamp_bucket_s": first_seen,
                    "last_seen_timestamp_bucket_s": last_seen,
                    "span_minutes": span_minutes,
                    "total_active_minutes": active,
                    "nonzero_in_minutes": nonzero,
                    "nonzero_ratio": nonzero_ratio,
                    "total_in_calls": total_in,
                    "total_out_calls": total_out,
                    "avg_in_calls": avg_in,
                    "max_in_calls": max_in,
                    "burst_ratio": burst_ratio,
                    "quality_score": quality_score,
                }
            )
    return rows


def main() -> None:
    args = parse_args()
    rows = load_rows(args.metadata_csv)
    if not rows:
        raise RuntimeError(f"No rows loaded from {args.metadata_csv}")

    output_csv = args.output_csv or args.metadata_csv.with_name("target_services.csv")
    summary_json = args.summary_json or args.metadata_csv.with_name("target_services_summary.json")

    hard_filtered = [
        row
        for row in rows
        if row["total_active_minutes"] >= args.min_active_minutes
        and row["nonzero_in_minutes"] >= args.min_nonzero_minutes
        and row["nonzero_ratio"] >= args.min_nonzero_ratio
    ]
    total_in_threshold = quantile(
        [row["total_in_calls"] for row in hard_filtered],
        args.min_total_in_quantile,
    )
    selected = [
        row
        for row in hard_filtered
        if row["total_in_calls"] >= total_in_threshold
    ]
    selected = sorted(
        selected,
        key=lambda row: (-row["quality_score"], -row["total_in_calls"], row["service_idx"]),
    )

    output_csv.parent.mkdir(parents=True, exist_ok=True)
    with output_csv.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(
            fh,
            fieldnames=[
                "service",
                "service_idx",
                "first_seen_timestamp_bucket_s",
                "last_seen_timestamp_bucket_s",
                "span_minutes",
                "total_active_minutes",
                "nonzero_in_minutes",
                "nonzero_ratio",
                "total_in_calls",
                "total_out_calls",
                "avg_in_calls",
                "max_in_calls",
                "burst_ratio",
                "quality_score",
            ],
        )
        writer.writeheader()
        for row in selected:
            writer.writerow(row)

    summary = {
        "metadata_csv": str(args.metadata_csv),
        "output_csv": str(output_csv),
        "total_services": len(rows),
        "hard_filtered_services": len(hard_filtered),
        "selected_services": len(selected),
        "thresholds": {
            "min_active_minutes": args.min_active_minutes,
            "min_nonzero_minutes": args.min_nonzero_minutes,
            "min_nonzero_ratio": args.min_nonzero_ratio,
            "min_total_in_quantile": args.min_total_in_quantile,
            "resolved_total_in_calls_threshold": total_in_threshold,
        },
    }
    summary_json.write_text(json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8")

    print(
        "[OK] "
        f"total={len(rows)} hard_filtered={len(hard_filtered)} "
        f"selected={len(selected)} threshold_total_in={total_in_threshold:.6f}"
    )


if __name__ == "__main__":
    main()
